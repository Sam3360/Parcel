//! Regenerates the example packages in /examples.
//! Run: cargo run -p parcel-workspace --example make_examples -- ../../examples
use parcel_core::cancel::CancelToken;
use parcel_workspace::collect::scan_paths;
use parcel_workspace::models::RefInput;
use parcel_workspace::ops::ExportRequest;
use parcel_workspace::Store;
use std::fs;
use std::path::PathBuf;

fn main() {
    let out = PathBuf::from(std::env::args().nth(1).unwrap_or_else(|| "examples".into()));
    fs::create_dir_all(&out).unwrap();
    let tmp = std::env::temp_dir().join(format!("parcel-examples-{}", std::process::id()));
    let _ = fs::remove_dir_all(&tmp);
    let w = |rel: &str, data: &str| {
        let p = tmp.join(rel);
        fs::create_dir_all(p.parent().unwrap()).unwrap();
        fs::write(&p, data).unwrap();
        p
    };
    let cancel = CancelToken::new();
    let noop = |_: &parcel_core::cancel::Progress| {};
    let mut s = Store::open_in_memory().unwrap();

    // 1. minimal
    let ws = s.create_workspace("Minimal example", "The smallest useful package: two files.", None).unwrap();
    let scan =
        scan_paths(&[w("hello.txt", "Hello from Parcel!\n"), w("data.csv", "name,score\nada,10\ngrace,12\n")], &cancel, &noop).unwrap();
    s.add_scanned(&ws.id, None, &scan).unwrap();
    let dest = out.join("minimal.parcel");
    let _ = fs::remove_file(&dest);
    s.export_workspace(&ws.id, &ExportRequest { dest, ..Default::default() }, &cancel, &noop).unwrap();

    // 2. research collection using a built-in template, notes, links, references and dependencies
    let ws = s
        .create_workspace("Research collection example", "Shows folders, notes, a link, references and dependencies.", Some("tpl-research"))
        .unwrap();
    let papers = s.ensure_folder_path(&ws.id, "Sources/Papers").unwrap();
    let data = s.ensure_folder_path(&ws.id, "Data").unwrap();
    let scan = scan_paths(&[w("paper.md", "# On packaging\n\nEverything that belongs together…\n")], &cancel, &noop).unwrap();
    s.add_scanned(&ws.id, Some(&papers), &scan).unwrap();
    let scan = scan_paths(&[w("measurements.csv", "t,value\n0,1.0\n1,1.5\n2,2.25\n")], &cancel, &noop).unwrap();
    s.add_scanned(&ws.id, Some(&data), &scan).unwrap();
    let files = s.list_entries(&ws.id).unwrap();
    let paper = files.iter().find(|e| e.name == "paper.md").unwrap().id.clone();
    let csv = files.iter().find(|e| e.name == "measurements.csv").unwrap().id.clone();
    s.create_link(&ws.id, None, "Project homepage", "https://example.com/project", "Not fetched by Parcel").unwrap();
    s.create_note(&ws.id, None, "Summary", "# Summary\n\nThe measurements support the paper.\n", Some(&csv)).unwrap();
    s.add_reference(
        &ws.id,
        RefInput {
            title: "The ZIP format".into(),
            url: "https://pkware.cachefly.net/webdocs/casestudies/APPNOTE.TXT".into(),
            description: "Container specification".into(),
            category: "Specifications".into(),
            entry_id: None,
        },
    )
    .unwrap();
    s.add_dependency(&ws.id, &paper, "entry", &csv, "The paper cites these measurements", true).unwrap();
    s.add_dependency(&ws.id, &paper, "external", "A Markdown renderer", "To read it nicely", false).unwrap();
    s.update_workspace(
        &ws.id,
        parcel_workspace::models::WorkspaceUpdate {
            notes: Some("# About this example\n\nGenerated by `make_examples`.\n".into()),
            ..Default::default()
        },
    )
    .unwrap();
    let dest = out.join("research-collection.parcel");
    let _ = fs::remove_file(&dest);
    s.export_workspace(&ws.id, &ExportRequest { dest, ..Default::default() }, &cancel, &noop).unwrap();
    let _ = fs::remove_dir_all(&tmp);
    println!("wrote examples to {}", out.display());
}
